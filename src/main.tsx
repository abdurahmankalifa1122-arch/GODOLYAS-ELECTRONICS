import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import App from './App.tsx';
import { ErrorBoundary } from './components/ErrorBoundary.tsx';
import './index.css';

declare global {
  interface Window {
    __GODOLYAS_MOUNTED__?: boolean;
  }
}

const rootElement = document.getElementById('root');

if (rootElement) {
  try {
    createRoot(rootElement).render(
      <StrictMode>
        <ErrorBoundary>
          <App />
        </ErrorBoundary>
      </StrictMode>
    );
    window.__GODOLYAS_MOUNTED__ = true;
  } catch (err) {
    console.error('Failed to mount GODOLYAS ELECTRONICS application:', err);
  }
}
